#include <iostream>
#include <string>
using namespace std;
int main() {
    // Integer data type
    int age = 18;
    //Float data type
    float marks = 95.7;
    //Double data type
    double percentage = 96.85;
    //String data type
    string name = "Warisha";
    //Character data type
    char grade = 'A';
    //Boolean data type
    bool isPassed =true;
    cout<< "Name:"<<name<<endl;
    cout<<"Age:"<<age<<endl;
    cout<<"Marks:"<<marks<<endl;
    cout<<"Percentage:"<<percentage<<endl;
    cout<<"Grade:"<<grade<<endl;
    cout<<"Is Passed:"<<isPassed<<endl;
    return 0;
}
